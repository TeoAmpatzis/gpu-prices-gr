// Writes docs/phase2/cpu-power-coverage.md: which desktop CPUs in public/data/cpu/latest.json have an
// official power-limit row in src/engine/data/cpuPower.ts. No timestamp, so the same data gives the same file.
// The chip-list part is copied from cpu-memory-coverage.ts (a script, not exported).
// Run: npm run cpu-power:coverage
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { cpuPowerRow } from '../../src/engine/data/cpuPower';
// Resolved from this file, not the working directory, so the script runs from anywhere.
const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');

const SOCKETS = ['AM5', 'AM4', 'LGA1700', 'LGA1851'];
const SERVER = /EPYC|Xeon|Threadripper|Opteron/i;
const OUT = join(ROOT, 'docs', 'phase2', 'cpu-power-coverage.md');

interface Listing { chip: string; socket: string | null }
const data = JSON.parse(readFileSync(join(ROOT, 'public', 'data', 'cpu', 'latest.json'), 'utf8')) as { listings: Listing[] };

const counts = new Map<string, Map<string, number>>(SOCKETS.map((s) => [s, new Map()]));
for (const l of data.listings) {
  const bySocket = l.socket ? counts.get(l.socket) : undefined;
  if (!bySocket || SERVER.test(l.chip)) continue;
  bySocket.set(l.chip, (bySocket.get(l.chip) ?? 0) + 1);
}

const host = (u: string) => new URL(u).hostname;

const lines: string[] = [
  '# CPU power limit coverage',
  '',
  'Desktop CPUs on AM5, AM4, LGA1700 and LGA1851 in `public/data/cpu/latest.json` (EPYC, Xeon, Threadripper and Opteron are left out) against `src/engine/data/cpuPower.ts`.',
  'Intel rows are "Maximum Turbo Power" (PL2) from intel.com. AMD "PPT" rows are absent: no official amd.com page states PPT for a model or a TDP class, so AMD chips are unknown (never computed from TDP).',
  'Generated by `npm run cpu-power:coverage`; do not edit by hand.',
  '',
  '## Totals',
  '',
  '| Socket | Chips | Covered | Uncovered |',
  '| --- | ---: | ---: | ---: |',
];
const tables: string[] = [];
let tc = 0, tcov = 0;
for (const s of SOCKETS) {
  const chips = [...counts.get(s)!.entries()].sort((a, b) => b[1] - a[1] || (a[0] < b[0] ? -1 : 1));
  const cov = chips.filter(([c]) => cpuPowerRow(c)).length;
  tc += chips.length; tcov += cov;
  lines.push(`| ${s} | ${chips.length} | ${cov} | ${chips.length - cov} |`);
  tables.push('', `## ${s}`, '', '| Chip | Listings | Covered | Kind | Watts | Source |', '| --- | ---: | --- | --- | ---: | --- |');
  for (const [chip, n] of chips) {
    const r = cpuPowerRow(chip);
    tables.push(r ? `| ${chip} | ${n} | yes | ${r.kind} | ${r.watts} | ${host(r.source)} |` : `| ${chip} | ${n} | no | — | — | — |`);
  }
}
lines.push(`| **All** | **${tc}** | **${tcov}** | **${tc - tcov}** |`, ...tables, '');
mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, lines.join('\n'));
console.log(`cpu-power coverage: ${tcov}/${tc} chips covered -> ${OUT}`);