// Writes docs/phase2/cpu-memory-coverage.md: which desktop CPUs in public/data/cpu/latest.json have an
// official memory row in src/engine/data/cpuMemory.ts. No timestamp, so the same data gives the same file.
// Run: npm run cpu-memory:coverage
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { cpuRow } from '../../src/engine/data/cpuMemory';

const SOCKETS = ['AM5', 'AM4', 'LGA1700', 'LGA1851'];
const SERVER = /EPYC|Xeon|Threadripper|Opteron/i;
const OUT = join(process.cwd(), 'docs', 'phase2', 'cpu-memory-coverage.md');

interface Listing { chip: string; socket: string | null }
const data = JSON.parse(readFileSync(join(process.cwd(), 'public', 'data', 'cpu', 'latest.json'), 'utf8')) as { listings: Listing[] };

const counts = new Map<string, Map<string, number>>(SOCKETS.map((s) => [s, new Map()]));
for (const l of data.listings) {
  const bySocket = l.socket ? counts.get(l.socket) : undefined;
  if (!bySocket || SERVER.test(l.chip)) continue;
  bySocket.set(l.chip, (bySocket.get(l.chip) ?? 0) + 1);
}

const speed = (v?: { sticks2?: number; sticks4?: number }, k?: 'sticks2' | 'sticks4') => (v?.[k as 'sticks2'] === undefined ? '—' : String(v[k as 'sticks2']));
const host = (u: string) => new URL(u).hostname;

const lines: string[] = [
  '# CPU memory coverage',
  '',
  'Desktop CPUs on AM5, AM4, LGA1700 and LGA1851 in `public/data/cpu/latest.json` (EPYC, Xeon, Threadripper and Opteron are left out) against `src/engine/data/cpuMemory.ts`.',
  'Generated by `npm run cpu-memory:coverage`; do not edit by hand.',
  '',
  '## Totals',
  '',
  '| Socket | Chips | Covered | Uncovered |',
  '| --- | ---: | ---: | ---: |',
];
const tables: string[] = [];
let tc = 0, tcov = 0;
for (const s of SOCKETS) {
  const chips = [...counts.get(s)!.entries()].sort((a, b) => b[1] - a[1] || (a[0] < b[0] ? -1 : 1));
  const cov = chips.filter(([c]) => cpuRow(c)).length;
  tc += chips.length; tcov += cov;
  lines.push(`| ${s} | ${chips.length} | ${cov} | ${chips.length - cov} |`);
  tables.push('', `## ${s}`, '', '| Chip | Listings | Covered | Generation | DDR4 2 sticks | DDR4 4 sticks | DDR5 2 sticks | DDR5 4 sticks | Source |', '| --- | ---: | --- | --- | ---: | ---: | ---: | ---: | --- |');
  for (const [chip, n] of chips) {
    const r = cpuRow(chip);
    tables.push(r
      ? `| ${chip} | ${n} | yes | ${r.generation} | ${speed(r.memory.DDR4, 'sticks2')} | ${speed(r.memory.DDR4, 'sticks4')} | ${speed(r.memory.DDR5, 'sticks2')} | ${speed(r.memory.DDR5, 'sticks4')} | ${host(r.source)} |`
      : `| ${chip} | ${n} | no | — | — | — | — | — | — |`);
  }
}
lines.push(`| **All** | **${tc}** | **${tcov}** | **${tc - tcov}** |`, ...tables, '');
mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, lines.join('\n'));
console.log(`cpu-memory coverage: ${tcov}/${tc} chips covered -> ${OUT}`);
