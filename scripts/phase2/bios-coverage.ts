// Writes docs/phase2/bios-coverage.md: chipset x CPU generation grid per desktop socket, from the mobo chipsets in
// public/data/mobo/latest.json against src/engine/data/bios.ts. No timestamp, so the same data gives the same file.
// Run: npm run bios:coverage
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { BIOS } from '../../src/engine/data/bios';
import type { CpuGeneration } from '../../src/engine/data/cpuMemory';

const SOCKETS: Record<string, CpuGeneration[]> = {
  AM4: ['ryzen-1000', 'ryzen-3000', 'ryzen-4000', 'ryzen-4000g', 'ryzen-5000', 'ryzen-5000g'],
  AM5: ['ryzen-7000', 'ryzen-8000', 'ryzen-8000g', 'ryzen-9000'],
  LGA1700: ['intel-12', 'intel-13', 'intel-14'],
  LGA1851: ['core-ultra-200s'],
};
const OUT = join(process.cwd(), 'docs', 'phase2', 'bios-coverage.md');
const up = (s: string) => s.toUpperCase();

interface Listing { chipset: string | null; socket: string | null }
const data = JSON.parse(readFileSync(join(process.cwd(), 'public', 'data', 'mobo', 'latest.json'), 'utf8')) as { listings: Listing[] };

const rowFor = (chipset: string, gen: CpuGeneration) => BIOS.find((r) => r.generation === gen && r.chipsets.some((c) => up(c) === up(chipset)));
const host = (u: string) => new URL(u).hostname;

const lines: string[] = [
  '# BIOS support coverage',
  '',
  'Chipsets of boards on AM4, AM5, LGA1700 and LGA1851 in `public/data/mobo/latest.json` (with listing counts) against `src/engine/data/bios.ts`.',
  'A cell is the official verdict (ok / update / unsupported); "—" = no official statement found, rule 13 stays unknown.',
  'Chipsets that only have a table row (no listing now) are shown with 0 listings.',
  'Generated by `npm run bios:coverage`; do not edit by hand.',
  '',
  '## Totals',
  '',
  '| Socket | Chipsets | Pairs | Covered pairs | Covered, weighted by listings | Listings |',
  '| --- | ---: | ---: | ---: | ---: | ---: |',
];
const tables: string[] = [];
let tp = 0, tcov = 0, tl = 0, tc = 0;
for (const [socket, gens] of Object.entries(SOCKETS)) {
  const counts = new Map<string, number>();
  for (const l of data.listings) if (l.socket === socket && l.chipset) counts.set(up(l.chipset), (counts.get(up(l.chipset)) ?? 0) + 1);
  for (const r of BIOS) if (gens.includes(r.generation)) for (const c of r.chipsets) if (!counts.has(up(c))) counts.set(up(c), 0);
  const chipsets = [...counts.entries()].sort((a, b) => b[1] - a[1] || (a[0] < b[0] ? -1 : 1));
  let pairs = 0, cov = 0, lw = 0, ls = 0;
  tables.push('', `## ${socket}`, '', `| Chipset | Listings | ${gens.join(' | ')} | Source |`, `| --- | ---: | ${gens.map(() => '---').join(' | ')} | --- |`);
  for (const [c, n] of chipsets) {
    const cells = gens.map((g) => rowFor(c, g)?.verdict ?? '—');
    const hosts = [...new Set(gens.flatMap((g) => { const r = rowFor(c, g); return r ? [host(r.source)] : []; }))].join(', ') || '—';
    pairs += gens.length; cov += cells.filter((v) => v !== '—').length;
    ls += n * gens.length; lw += n * cells.filter((v) => v !== '—').length;
    tables.push(`| ${c} | ${n} | ${cells.join(' | ')} | ${hosts} |`);
  }
  lines.push(`| ${socket} | ${chipsets.length} | ${pairs} | ${cov} | ${ls ? Math.round((100 * lw) / ls) : 0}% | ${chipsets.reduce((s, [, n]) => s + n, 0)} |`);
  tc += chipsets.length; tp += pairs; tcov += cov; tl += chipsets.reduce((s, [, n]) => s + n, 0);
}
lines.push(`| **All** | **${tc}** | **${tp}** | **${tcov}** | | **${tl}** |`, ...tables, '');
mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, lines.join('\n'));
console.log(`bios coverage: ${tcov}/${tp} chipset x generation pairs covered -> ${OUT}`);
