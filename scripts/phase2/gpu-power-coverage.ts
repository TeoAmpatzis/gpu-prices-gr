// Writes docs/phase2/gpu-power-coverage.md: which consumer graphics chips in public/data/gpu/latest.json have an
// official power row in src/engine/data/gpuPower.ts. No timestamp, so the same data gives the same file.
// Workstation chips are left out with the same pattern as the GPU category's own `pro` test (GPU_WORKSTATION in
// src/lib/categories.tsx, which pulls in React/JSX and is not imported here) plus the Quadro/Radeon PRO/Arc Pro names.
// Run: npm run gpu-power:coverage
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { gpuPowerRow } from '../../src/engine/data/gpuPower';
// Resolved from this file, not the working directory, so the script runs from anywhere.
const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');

const WORKSTATION = /^(RTX PRO |RTX A\d|T\d|RTX \d{4} (Ada|\(Pro\)))|Quadro|Radeon PRO|Arc Pro/;
const BRANDS = ['NVIDIA', 'AMD', 'Intel'];
const OUT = join(ROOT, 'docs', 'phase2', 'gpu-power-coverage.md');

interface Listing { chip: string; brand: string }
const data = JSON.parse(readFileSync(join(ROOT, 'public', 'data', 'gpu', 'latest.json'), 'utf8')) as { listings: Listing[] };

const counts = new Map<string, Map<string, number>>(BRANDS.map((b) => [b, new Map()]));
for (const l of data.listings) {
  const byBrand = counts.get(l.brand);
  if (!byBrand || WORKSTATION.test(l.chip)) continue;
  byBrand.set(l.chip, (byBrand.get(l.chip) ?? 0) + 1);
}

const fig = (v?: number) => (v === undefined ? '—' : String(v));
const host = (u: string) => new URL(u).hostname;

const lines: string[] = [
  '# GPU power coverage',
  '',
  'Consumer graphics chips in `public/data/gpu/latest.json` (workstation chips such as RTX PRO, RTX A, T-series, RTX ... Ada and Quadro are left out) against `src/engine/data/gpuPower.ts`.',
  'Generated by `npm run gpu-power:coverage`; do not edit by hand.',
  '',
  '## Totals',
  '',
  '| Brand | Chips | Covered | Uncovered |',
  '| --- | ---: | ---: | ---: |',
];
const tables: string[] = [];
let tc = 0, tcov = 0;
for (const b of BRANDS) {
  const chips = [...counts.get(b)!.entries()].sort((a, c) => c[1] - a[1] || (a[0] < c[0] ? -1 : 1));
  const cov = chips.filter(([c]) => gpuPowerRow(c)).length;
  tc += chips.length; tcov += cov;
  lines.push(`| ${b} | ${chips.length} | ${cov} | ${chips.length - cov} |`);
  tables.push('', `## ${b}`, '', '| Chip | Listings | Covered | Board power (W) | Maker PSU (W) | Source |', '| --- | ---: | --- | ---: | ---: | --- |');
  for (const [chip, n] of chips) {
    const r = gpuPowerRow(chip);
    tables.push(r
      ? `| ${chip} | ${n} | yes | ${fig(r.boardPowerW)} | ${fig(r.makerPsuW)} | ${host(r.source)} |`
      : `| ${chip} | ${n} | no | — | — | — |`);
  }
}
lines.push(`| **All** | **${tc}** | **${tcov}** | **${tc - tcov}** |`, ...tables, '');
mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, lines.join('\n'));
console.log(`gpu-power coverage: ${tcov}/${tc} chips covered -> ${OUT}`);
