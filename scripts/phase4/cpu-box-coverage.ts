// Writes docs/phase4/cpu-box-coverage.md: which desktop CPUs sold as Box in public/data/cpu/latest.json have a
// row in src/engine/data/cpuBox.ts, per family, and where a shop's stated value disagrees with the maker's page.
// No timestamp, so the same data gives the same file. Run: npm run cpu-box:coverage
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { boxCooler } from '../../src/engine/data/cpuBox';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT = join(ROOT, 'docs', 'phase4', 'cpu-box-coverage.md');
const SERVER = /EPYC|Xeon|Threadripper|Opteron/i;

interface Listing { chip: string; packaging: string | null; coolerIncluded: boolean | null }
const data = JSON.parse(readFileSync(join(ROOT, 'public', 'data', 'cpu', 'latest.json'), 'utf8')) as { listings: Listing[] };

const family = (chip: string): string => {
  let m = /^Ryzen \d (\d)\d{3}/.exec(chip);
  if (m) return `Ryzen ${m[1]}000`;
  if (/^Athlon/.test(chip)) return 'Athlon';
  if (/^Core Ultra/.test(chip)) return 'Core Ultra';
  m = /^Core i\d-(\d{1,2})\d{3}/.exec(chip);
  if (m) return `Core ${m[1]}th gen`;
  if (/^(Pentium|Celeron)/.test(chip)) return 'Pentium/Celeron';
  return 'Other';
};

const box = data.listings.filter((l) => l.packaging === 'Box' && !SERVER.test(l.chip));
const chips = new Map<string, { n: number; stated: Set<boolean> }>();
for (const l of box) {
  const e = chips.get(l.chip) ?? { n: 0, stated: new Set<boolean>() };
  e.n++;
  if (l.coolerIncluded !== null) e.stated.add(l.coolerIncluded);
  chips.set(l.chip, e);
}

const fam = new Map<string, { chips: number; covered: number }>();
const missing: string[] = [];
const disagree: string[] = [];
for (const [chip, e] of [...chips.entries()].sort((a, b) => b[1].n - a[1].n || (a[0] < b[0] ? -1 : 1))) {
  if (e.n < 2) continue; // target: every Box chip with at least 2 listings
  const f = family(chip), row = boxCooler(chip);
  const s = fam.get(f) ?? { chips: 0, covered: 0 };
  s.chips++;
  if (row) s.covered++; else missing.push(`| ${chip} | ${e.n} | ${f} |`);
  fam.set(f, s);
}
for (const [chip, e] of chips) {
  const row = boxCooler(chip);
  if (row) for (const v of e.stated) if (v !== row.included) disagree.push(`| ${chip} | shop says ${v ? 'cooler' : 'no cooler'} | page says ${row.included ? row.cooler : 'Not Included'} |`);
}

let tc = 0, tcov = 0;
const famLines = [...fam.entries()].sort().map(([f, s]) => { tc += s.chips; tcov += s.covered; return `| ${f} | ${s.chips} | ${s.covered} | ${s.chips - s.covered} |`; });
const lines = [
  '# Box CPU cooler coverage',
  '',
  'Desktop Box CPU chips with at least 2 listings in `public/data/cpu/latest.json` (EPYC, Xeon, Threadripper, Opteron left out) against `src/engine/data/cpuBox.ts`.',
  'Generated by `npm run cpu-box:coverage`; do not edit by hand.',
  '',
  '## Per family',
  '',
  '| Family | Chips | With a row | Without |',
  '| --- | ---: | ---: | ---: |',
  ...famLines,
  `| **All** | **${tc}** | **${tcov}** | **${tc - tcov}** |`,
  '',
  '## Chips without a row (cooler stays "not stated")',
  '',
  'AMD: the page lacks the "Thermal Solution (PIB)" field or amd.com has no product page for it. Intel: one intel.com download got HTTP 403 and a second attempt was blocked by the permission system (nothing more was tried), and only an intel.com page that names the boxed cooler counts (owner 2026-10-25), so no Intel chip has a row.',
  '',
  '| Chip | Box listings | Family |',
  '| --- | ---: | --- |',
  ...missing,
  '',
  '## Shop values that disagree with the maker page (shop value kept)',
  '',
  '| Chip | Shop | Maker page |',
  '| --- | --- | --- |',
  ...(disagree.length ? disagree : ['| none | | |']),
  '',
];
mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, lines.join('\n'));
console.log(`cpu-box coverage: ${tcov}/${tc} chips (>=2 Box listings) have a row, ${disagree.length} disagreement(s) -> ${OUT}`);
